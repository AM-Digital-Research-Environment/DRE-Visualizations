/** Root entries not worth showing. */
const HIDE = new Set(['.editorconfig', '.gitattributes', '.gitignore', '.nvmrc']);

/** Tracked and new (unignored) files that exist: the same answer before and after `git add`. */
function trackedFiles() {
  return execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', '--deduplicate'],
    { cwd: ROOT, encoding: 'utf8' })
    .split('\n')
    .filter(Boolean)
    .filter((path) => !path.startsWith('.impeccable/') && !HIDE.has(path))
    .filter((path) => existsSync(join(ROOT, path)));
}

/** Nested {name: node}; a file is null. */
function buildTree(paths) {
  const root = {};
  for (const path of paths) {
    const parts = path.split('/');
    let node = root;
    parts.forEach((part, i) => {
      if (i === parts.length - 1) node[part] = null;
      else node = (node[part] ||= {});
    });
  }
  return root;
}

function countFiles(node) {
  return Object.values(node).reduce((n, child) => n + (child === null ? 1 : countFiles(child)), 0);
}

/** Directories first, then files, each alphabetically. */
function entriesOf(node) {
  return Object.keys(node).sort((a, b) => {
    const dirA = node[a] !== null;
    const dirB = node[b] !== null;
    return dirA !== dirB ? (dirA ? -1 : 1) : a.localeCompare(b);
  });
}

const used = new Set();

function render(node, prefix, base, rows) {
  const names = entriesOf(node);
  names.forEach((name, i) => {
    const last = i === names.length - 1;
    const path = base ? `${base}/${name}` : name;
    const isDir = node[name] !== null;
    let note = ANNOTATIONS[path] ?? null;
    if (note) used.add(path);
    const summary = isDir ? SUMMARIZE[`${path}/`] : null;
    if (summary) {
      used.add(`${path}/`);
      const n = countFiles(node[name]);
      note = `${n} file${n === 1 ? '' : 's'} — ${summary}`;
    }
    rows.push({ text: prefix + (last ? '└── ' : '├── ') + (isDir ? `${name}/` : name), note });
    if (isDir && !summary) render(node[name], prefix + (last ? '    ' : '│   '), path, rows);
  });
}

function tree() {
  const rows = [{ text: 'DreVisualizations/', note: null }];
  render(buildTree(trackedFiles()), '', '', rows);
  const width = Math.max(...rows.map((row) => (row.note ? row.text.length : 0))) + 2;
  const body = rows.map((row) => (row.note ? `${row.text.padEnd(width)}# ${row.note}` : row.text)).join('\n');
  const orphans = [...Object.keys(ANNOTATIONS), ...Object.keys(SUMMARIZE)].filter((path) => !used.has(path));
  return { block: '```\n' + body + '\n```', orphans };
}

const current = readFileSync(TARGET, 'utf8').replace(/\r\n/g, '\n');
const start = current.indexOf(BEGIN);
const stop = current.indexOf(END);
if (start === -1 || stop === -1) {
  console.error(`README.md lacks the ${BEGIN} / ${END} markers.`);
  process.exit(1);
}
const { block, orphans } = tree();
if (orphans.length) {
  console.error('Repository tree: annotations for paths that are not tracked (update scripts/build-tree.mjs):');
  for (const path of orphans) console.error('  ' + path);
  process.exit(1);
}
const next = current.slice(0, start + BEGIN.length) + '\n\n' + block + '\n\n' + current.slice(stop);
const files = trackedFiles().length;
if (process.argv.includes('--check')) {
  if (next !== current) {
    console.error('Repository tree: README.md does not match the repository; run npm run build:tree.');
    process.exit(1);
  }
  console.log(`Repository tree: README.md matches ${files} files.`);
} else {
  writeFileSync(TARGET, next, 'utf8');
  console.log(`Repository tree: wrote ${files} files into README.md.`);
}
